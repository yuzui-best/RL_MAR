"""Audit archived results without executing candidates or exposing hidden vectors."""
import argparse
from collections import Counter, defaultdict
import hashlib
import io
import json
from pathlib import Path
import re
import tarfile

import numpy as np
from scipy.stats import binomtest

MODELS = ['gpt-4o', 'gpt-4o-mini', 'deepseek-v3.2', 'qwen3.5-9b', 'deepseek-v4-flash']
SCALARS = {'BOOL', 'BYTE', 'SINT', 'USINT', 'INT', 'UINT', 'WORD', 'DINT',
           'UDINT', 'DWORD', 'LINT', 'ULINT', 'LWORD', 'REAL', 'LREAL', 'TIME'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def supported_type(value):
    value = value.upper().strip()
    if value in SCALARS:
        return True
    match = re.fullmatch(r'ARRAY\s*\[\s*-?\d+\s*\.\.\s*-?\d+(?:\s*,\s*-?\d+\s*\.\.\s*-?\d+)?\s*\]\s*OF\s+(.+)', value)
    return bool(match and match[1] in SCALARS)


def holm(rows):
    last = 0.0
    for rank, row in enumerate(sorted(rows, key=lambda r: r['mcnemar_exact_p'])):
        last = max(last, min(1.0, (len(rows) - rank) * row['mcnemar_exact_p']))
        row['holm_p'] = last


def paired(a, b, indices):
    difference = a.astype(float) - b.astype(float)
    wins = int(np.sum(difference == 1))
    losses = int(np.sum(difference == -1))
    interval = np.quantile(difference[indices].mean(axis=1) * 100, [0.025, 0.975])
    return dict(n=len(a), rlmar=int(a.sum()), autoplc=int(b.sum()), wins=wins,
                losses=losses, both=int(np.sum(a & b)), neither=int(np.sum(~a & ~b)),
                difference_pp=float(difference.mean() * 100), ci95_pp=interval.tolist(),
                mcnemar_exact_p=float(binomtest(wins, wins + losses).pvalue) if wins + losses else 1.0)


def export_paper(output, paper):
    lines = ['# Paired Statistics and Domain Results', '',
             'Generated by `experiments/paper/audit_saved_evidence.py`. Values use saved primary generations.', '',
             '95% pointwise paired percentile intervals use 50,000 bootstrap samples (seed 20260907).',
             'Pooled intervals resample task identities jointly across five fixed backbones.',
             'McNemar tests are two-sided and exact; Holm families contain five backbones per endpoint.',
             'These intervals represent task-sampling uncertainty conditional on the saved outputs, not generation variance.', '']
    tex = [r'\documentclass{article}', r'\usepackage[margin=20mm]{geometry}', r'\usepackage{fontspec}',
           r'\setmainfont{Times New Roman}', r'\usepackage{booktabs}', r'\begin{document}',
           r'\section*{Paired Functional94 Results}',
           r'RL-MAR minus AutoPLC. Pointwise 95\% paired task bootstrap intervals; 50,000 samples, seed 20260907.',
           r'Two-sided exact McNemar tests with Holm adjustment over the five backbones.',
           r'\begin{center}\small\begin{tabular}{lrrrrr}\toprule',
           r'Backbone & Wins/losses & Difference (pp) & 95\% CI (pp) & $p$ & Holm $p$ \\ \midrule']
    for selection, stats in output['statistics'].items():
        for endpoint, values in stats.items():
            lines += [f'## {selection}: {endpoint}', '',
                '| Backbone | RL-MAR / AutoPLC | Wins / losses | Difference (pp) | 95% CI (pp) | Exact p | Holm p |',
                '| --- | --- | --- | --- | --- | --- | --- |']
            for r in values['backbones']:
                lo, hi = r['ci95_pp']
                lines.append(f"| {r['model']} | {r['rlmar']}/{r['n']} / {r['autoplc']}/{r['n']} | {r['wins']} / {r['losses']} | {r['difference_pp']:.2f} | [{lo:.2f}, {hi:.2f}] | {r['mcnemar_exact_p']:.6f} | {r['holm_p']:.6f} |")
                if selection=='main94' and endpoint=='functional':
                    tex.append(f"{r['model']} & {r['wins']}/{r['losses']} & {r['difference_pp']:.2f} & [{lo:.2f}, {hi:.2f}] & {r['mcnemar_exact_p']:.3f} & {r['holm_p']:.3f}" + r' \\')
            pooled = values['pooled']
            lo, hi = pooled['ci95_pp']
            lines += ['', f"Pooled: {pooled['difference_pp']:.2f} pp [{lo:.2f}, {hi:.2f}], {pooled['tasks']} task clusters / {pooled['pairs']} pairs.", '']
    pooled=output['statistics']['main94']['functional']['pooled']
    tex += [r'\midrule', f"Pooled (94 clusters) & & {pooled['difference_pp']:.2f} & [{pooled['ci95_pp'][0]:.2f}, {pooled['ci95_pp'][1]:.2f}] & &"+r' \\',
            r'\bottomrule\end{tabular}\end{center}',
            r'Intervals condition on saved generations and treat the benchmark tasks as a sample of a task population. Two generation runs do not reliably estimate generation variance.', r'\end{document}']
    lines += ['## Inferred Domains (Descriptive)', '',
              '| Backbone | Domain | Tasks | Direct | AutoPLC | LLM4PLC | RL-MAR |',
              '| --- | --- | --- | --- | --- | --- | --- |']
    for r in output['domain_results']:
        lines.append(f"| {r['model']} | {r['domain']} | {r['n']} | {r['Direct Generation']} | {r['AutoPLC']} | {r['LLM4PLC']} | {r['RL-MAR']} |")
    lines += ['', 'Domain labels are inferred by the deployed router, not the benchmark category table.',
              'No domain hypothesis tests or learned-router versus rule-table effect are inferred.', '',
              '## Sensitivity Membership', '', output['protocol']['subset_rule'], '',
              'Excluded: '+', '.join(sorted(output['subset']['excluded']))+'.',
              'The retained med_57 still exposes generated nested-FB ABI failures; the subset is not certified interface-supported.', '',
              '## Provenance', '', '```json', json.dumps(output['hashes'],indent=2), '```', '']
    (paper/'resubmission/PAIRED_STATISTICS_20260907.md').write_text('\n'.join(lines))
    (paper/'resubmission/paired_statistics_preview.tex').write_text('\n'.join(tex)+'\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--results', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--paper', type=Path)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    data = json.loads((args.results / 'unified_results.json').read_text())
    groups = {(g['method'], g['model'], g['run']): g for g in data['groups']}
    assert len(groups) == 25
    refs = json.loads((args.results / 'reference_results.json').read_text())
    with tarfile.open(args.results / 'evaluation_archive.tar.gz') as archive:
        snapshot_bytes = archive.extractfile('source_snapshot.tar.gz').read()
        reference_requests = {
            t['task_id']: json.load(archive.extractfile('responses/reference_reference_pilot/' + t['task_id'] + '.request.json'))
            for t in refs['groups'][0]['tasks']}
    with tarfile.open(fileobj=io.BytesIO(snapshot_bytes)) as archive:
        manifest_path = next(n for n in archive.getnames() if n.endswith('/data/plc94.functional.v1.3.jsonl'))
        manifest_bytes = archive.extractfile(manifest_path).read()
        assert sha(manifest_bytes) == data['manifest_sha256']
        tasks = {t['task_id']: t for t in map(json.loads, manifest_bytes.splitlines())}
        records = {}
        for group in data['groups']:
            if group['method'] != 'RL-MAR':
                continue
            for task_id in tasks:
                name = group['provenance']['source'].lstrip('/') + '/' + task_id + '.json'
                raw = archive.extractfile(name).read()
                assert sha(raw) == group['provenance']['record_hashes'][task_id + '.json']
                records[group['model'], group['run'], task_id] = json.loads(raw)
    ids = sorted(tasks)
    for g in groups.values():
        assert len(g['tasks']) == len({r['task_id'] for r in g['tasks']}) == 94
        assert {r['task_id'] for r in g['tasks']} == set(ids)
        assert sum(r['status'] == 'PASS' for r in g['tasks']) == g['summary']['passed']
        assert sum(r['compiled'] for r in g['tasks']) == g['summary']['compiled']
    for task_id in ids:
        vectors = {r['test_vector_sha256'] for g in groups.values() for r in g['tasks']
                   if r['task_id'] == task_id and 'test_vector_sha256' in r}
        assert len(vectors) == 1
    # Membership uses declarations only, never generated sources or outcomes.
    exclusions = {}
    for task_id, task in tasks.items():
        reasons = []
        for d in task['pou_declarations']:
            if d['section'] == 'inout':
                reasons.append('IN_OUT')
            if not supported_type(d['type']):
                reasons.append('nonprimitive_or_unsupported_declaration')
        if reasons:
            exclusions[task_id] = sorted(set(reasons))
    subset = [i for i in ids if i not in exclusions]
    def outcomes(method, model, run, metric, selection):
        rows = {r['task_id']: r for r in groups[method, model, run]['tasks']}
        return np.array([rows[i]['status'] == 'PASS' if metric == 'functional' else rows[i]['compiled'] for i in selection], dtype=bool)
    rng = np.random.default_rng(20260907)
    stats = {}
    for name, selection in [('main94', ids), ('primitive_no_inout', subset)]:
        indices = rng.integers(0, len(selection), size=(50000, len(selection)))
        results = {}
        for metric in ['functional', 'compilation']:
            rows, differences = [], []
            for model in MODELS:
                a = outcomes('RL-MAR', model, 'primary', metric, selection)
                b = outcomes('AutoPLC', model, 'primary', metric, selection)
                rows.append(dict(model=model, **paired(a, b, indices)))
                differences.append(a.astype(float) - b.astype(float))
            holm(rows)
            # Resample task identities jointly across all five fixed backbones.
            cluster_difference = np.array(differences).mean(axis=0)
            results[metric] = dict(backbones=rows, pooled=dict(
                tasks=len(selection), pairs=5 * len(selection),
                difference_pp=float(cluster_difference.mean() * 100),
                ci95_pp=np.quantile(cluster_difference[indices].mean(axis=1) * 100, [0.025, 0.975]).tolist()))
        stats[name] = results
    repetitions = []
    for model in MODELS:
        a = outcomes('RL-MAR', model, 'primary', 'functional', ids)
        b = outcomes('RL-MAR', model, 'confirmation', 'functional', ids)
        repetitions.append(dict(model=model, primary=int(a.sum()), confirmation=int(b.sum()),
                                both=int((a & b).sum()), changed=int((a != b).sum())))
    exposure = []
    for (method, model, run), group in groups.items():
        errors = Counter()
        for row in group['tasks']:
            diagnostic = row.get('diagnostic', '')
            if 'unsupported C ABI' in diagnostic:
                errors['unsupported_abi'] += 1
            if 'missing field' in diagnostic or 'missing IN_OUT' in diagnostic:
                errors['missing_field'] += 1
            if row.get('returncode') == -11:
                errors['sigsegv'] += 1
        exposure.append(dict(method=method, model=model, run=run, **errors))
    reference_audit = []
    for row in refs['groups'][0]['tasks']:
        task_id = row['task_id']
        request = reference_requests[task_id]
        assert sha(request['source'].encode()) == row['extracted_sha256']
        reference_audit.append(dict(task_id=task_id, status=row['status'], compiled=row['compiled'],
            source_sha256=row['extracted_sha256'], request_task_equal_manifest=request['task'] == tasks[task_id],
            mismatching_fields=sorted({c['first_mismatch']['field'] for c in row.get('checks', []) if c.get('first_mismatch')}),
            diagnostic=row.get('diagnostic'), returncode=row.get('returncode')))
    domain_rows, route_rows, cases, deviations = [], [], [], []
    for model in MODELS:
        by_domain = defaultdict(list)
        for task_id in ids:
            record = records[model, 'primary', task_id]
            by_domain[record['inferred_domain']].append(task_id)
        for domain, selection in sorted(by_domain.items()):
            row = dict(model=model, domain=domain, n=len(selection))
            for method in ['Direct Generation', 'AutoPLC', 'LLM4PLC', 'RL-MAR']:
                row[method] = int(outcomes(method, model, 'primary', 'functional', selection).sum())
            domain_rows.append(row)
    for run in ['primary', 'confirmation']:
        patterns = Counter()
        for model in MODELS:
            for task_id in ids:
                r = records[model, run, task_id]
                a = r['execution_action']
                role_events = [e for e in r['execution']['events'] if e['kind'] == 'role']
                initial = [e for e in role_events if not e['purpose'].startswith('Repair')]
                roles = tuple(e['role'] for e in initial)
                patterns[(r['inferred_domain'], tuple(a['role_indices']), roles, a['agent_count'])] += 1
                if not (a['topology_index'] == 2 and a['rounds'] == 1 and a['repair_budget'] == 1) or a != r['route_action']:
                    deviations.append(dict(model=model, run=run, task_id=task_id, route_action=r['route_action'], execution_action=a))
                if run == 'primary' and model == 'gpt-4o':
                    cases.append(dict(task_id=task_id, domain=r['inferred_domain'], roles=list(roles),
                        action=a, events=[{k:e[k] for k in ['kind', 'role', 'parents', 'status', 'response_sha256'] if k in e}
                                         for e in r['execution']['events']],
                        unified_status=next(t['status'] for t in groups['RL-MAR', model, run]['tasks'] if t['task_id']==task_id),
                        source_record_sha256=groups['RL-MAR',model,run]['provenance']['record_hashes'][task_id+'.json']))
        for (domain, indices_, roles, count), n in sorted(patterns.items()):
            route_rows.append(dict(run=run, domain=domain, role_indices=list(indices_), observed_roles=list(roles), agent_count=count, records=n))
    output = dict(protocol=dict(seed=20260907, bootstrap_replicates=50000,
        interval='paired task percentile bootstrap; pooled resamples 94 task clusters across five fixed backbones',
        multiplicity='Holm across five backbones separately for functional primary and secondary compilation; sensitivity is exploratory',
        uncertainty='conditional on saved generations; task-resampling inference assumes benchmark tasks represent a task population; does not estimate generation variance',
        subset_rule='all manifest declarations primitive scalar or fixed 1D/2D primitive array, with no IN_OUT; outcome-independent conservative scope, not a certificate of runtime support'),
        hashes=dict(manifest=data['manifest_sha256'], engine=data['engine_sha256'], normalizer=data['normalizer_sha256'], snapshot=sha(snapshot_bytes),
                    unified=sha((args.results/'unified_results.json').read_bytes()), script=sha(Path(__file__).read_bytes())),
        statistics=stats, subset=dict(included=subset, excluded=exclusions),
        reference_audit=reference_audit, interface_exposure=exposure, repetitions=repetitions,
        domain_results=domain_rows, observed_routes=route_rows, traceable_cases=cases, route_deviations=deviations)
    (args.out/'evidence_analysis.json').write_text(json.dumps(output, indent=2)+'\n')
    if args.paper:
        export_paper(output, args.paper)
    print(json.dumps(dict(main_functional=stats['main94']['functional']['pooled'], subset_n=len(subset),
                          reference_candidates=len(reference_audit), verified_route_records=len(records),
                          route_deviations=len(deviations)), indent=2))


if __name__ == '__main__':
    main()
