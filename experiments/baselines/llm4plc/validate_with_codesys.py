"""
CODESYS Compilation Validator for Generated PLC Code

This script validates ST code generated by Single Agent Baseline using
the CODESYS compilation service to get real compilation results.
"""

import json
import os
import sys
import time
import requests
import logging
import argparse
import re
from pathlib import Path
from typing import Dict, List, Any


class CompilerInfrastructureError(RuntimeError):
    """The compiler service was unavailable; generated code was not assessed."""

# Add parent directory to path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..')))

class CODESYSValidator:
    """Validate ST code using CODESYS compilation service"""

    def __init__(self, server_host: str = None, server_port: int = None):
        """
        Initialize the CODESYS validator

        Args:
            server_host: CODESYS server host (auto-detect if None)
            server_port: CODESYS server port (auto-detect if None)
        """
        self.server_host = server_host
        self.server_port = server_port
        self.api_key = "admin"
        self.base_url = None
        self.session = None

        # Setup logging
        self.logger = self._setup_logging()

        # Initialize connection
        self._initialize_connection()

    def _setup_logging(self):
        """Setup logging configuration"""
        logger = logging.getLogger("CODESYSValidator")
        logger.setLevel(logging.INFO)

        # Console handler
        console_handler = logging.StreamHandler()
        console_handler.setLevel(logging.INFO)
        formatter = logging.Formatter('%(asctime)s - %(levelname)s - %(message)s')
        console_handler.setFormatter(formatter)
        logger.addHandler(console_handler)

        return logger

    def _get_server_address_from_log(self) -> tuple:
        """Extract server address from CODESYS log file"""
        log_path = Path(__file__).parent.parent.joinpath("CODESYSCompileService/codesys_api_server.log")

        if not log_path.exists():
            self.logger.warning(f"CODESYS log file not found at {log_path}")
            return None, None

        try:
            log_text = log_path.read_text(encoding="utf-8", errors="ignore")
            host_match = re.search(r"HOST:\s*([0-9]+\.[0-9]+\.[0-9]+\.[0-9]+)", log_text)
            port_match = re.search(r"PORT:\s*(\d+)", log_text)

            if host_match and port_match:
                host = host_match.group(1)
                port = int(port_match.group(1))
                self.logger.info(f"Auto-detected CODESYS server: {host}:{port}")
                return host, port
            else:
                self.logger.warning("Could not extract HOST and PORT from log file")
                return None, None

        except Exception as e:
            self.logger.error(f"Error reading log file: {e}")
            return None, None

    def _initialize_connection(self):
        """Initialize connection to CODESYS server"""
        # Auto-detect server address if not provided
        if self.server_host is None or self.server_port is None:
            detected_host, detected_port = self._get_server_address_from_log()
            self.server_host = detected_host or "127.0.0.1"
            self.server_port = detected_port or 9000

        # Setup base URL and session
        self.base_url = f"http://{self.server_host}:{self.server_port}/api/v1"
        self.session = requests.Session()
        self.session.headers.update({
            'Authorization': f'ApiKey {self.api_key}',
            'Content-Type': 'application/json'
        })

        self.logger.info(f"CODESYS Validator initialized: {self.base_url}")

    def validate_code(self, code: str, task_id: str = "unknown") -> Dict[str, Any]:
        """
        Validate ST code using CODESYS compilation service

        Args:
            code: ST code to validate
            task_id: Task identifier for logging

        Returns:
            Validation result dictionary
        """
        # 检查空代码
        if not code or not code.strip():
            self.logger.warning(f"Empty code detected for task {task_id}, marking as failed")
            return {
                "task_id": task_id,
                "compilation_success": False,
                "api_success": False,
                "errors": [{"ErrorDesc": "Empty code generated"}],
                "validation_time": 0.0,
                "response_status": None,
                "full_response": None
            }

        url = f"{self.base_url}/pou/workflow"
        payload = {"Code": code}

        try:
            start_time = time.time()
            response = self.session.post(url, json=payload, timeout=120)
            duration = time.time() - start_time

            if response.status_code == 200:
                result = response.json()

                # Parse validation result
                # Fixed: Changed default from True to False to prevent false positives
                success = result.get("Success", False)
                errors = result.get("Errors", [])

                # Determine if compilation was successful
                compilation_success = success and not errors

                return {
                    "task_id": task_id,
                    "compilation_success": compilation_success,
                    "api_success": success,
                    "errors": errors,
                    "validation_time": duration,
                    "response_status": response.status_code,
                    "full_response": result
                }
            else:
                self.logger.error(f"API call failed for task {task_id}: {response.status_code}")
                raise CompilerInfrastructureError(
                    f"INFRA_ERROR: compiler service returned HTTP {response.status_code}"
                )

        except requests.exceptions.Timeout:
            self.logger.error(f"Timeout validating task {task_id}")
            raise CompilerInfrastructureError(
                "INFRA_ERROR: compiler service request timed out"
            )
        except requests.exceptions.RequestException as e:
            self.logger.error(f"Compiler service unavailable for task {task_id}: {e}")
            raise CompilerInfrastructureError(
                f"INFRA_ERROR: compiler service unavailable: {e}"
            ) from e
        except CompilerInfrastructureError:
            raise
        except Exception as e:
            self.logger.error(f"Exception validating task {task_id}: {e}")
            raise CompilerInfrastructureError(
                f"INFRA_ERROR: invalid compiler service response: {e}"
            ) from e

    def validate_batch(self, results: List[Dict]) -> List[Dict]:
        """
        Validate a batch of generated code results

        Args:
            results: List of Single Agent baseline results

        Returns:
            Enhanced results with CODESYS validation
        """
        validated_results = []
        total_tasks = len(results)

        self.logger.info(f"Starting CODESYS validation for {total_tasks} tasks...")

        for i, result in enumerate(results, 1):
            task_id = result.get('task_id', f'task_{i}')
            generated_code = result.get('generated_code', '')

            self.logger.info(f"[{i}/{total_tasks}] Validating {task_id}")

            # Skip if no code was generated
            if not generated_code or generated_code == "":
                self.logger.warning(f"Skipping {task_id}: No generated code")
                enhanced_result = result.copy()
                enhanced_result['codesys_validation'] = {
                    "compilation_success": False,
                    "errors": [{"ErrorDesc": "No code generated"}],
                    "validation_time": 0.0
                }
                validated_results.append(enhanced_result)
                continue

            # Validate the code
            validation_result = self.validate_code(generated_code, task_id)

            # Enhance the original result
            enhanced_result = result.copy()
            enhanced_result['codesys_validation'] = validation_result
            # Support both 'passed' and 'compilation_success' fields for compatibility
            enhanced_result['codesys_passed'] = validation_result.get('passed', validation_result.get('compilation_success', False))

            validated_results.append(enhanced_result)

            # Log progress
            if i % 5 == 0 or i == total_tasks:
                passed_count = sum(1 for r in validated_results if r.get('codesys_passed', False))
                pass_rate = passed_count / i * 100
                self.logger.info(f"Progress: {i}/{total_tasks} | CODESYS Pass Rate: {pass_rate:.1f}%")

            # Small delay to avoid overwhelming the server
            time.sleep(0.5)

        return validated_results

    def generate_comparison_report(self, antlr_results: List[Dict], codesys_results: List[Dict]):
        """Generate comparison between ANTLR and CODESYS validation"""
        print("\n" + "=" * 100)
        print(" " * 25 + "ANTLR vs CODESYS Validation Comparison")
        print("=" * 100)

        # Calculate ANTLR metrics
        antlr_pass = sum(1 for r in antlr_results if r.get('is_solved', False))
        antlr_total = len(antlr_results)
        antlr_rate = antlr_pass / antlr_total * 100 if antlr_total > 0 else 0

        # Calculate CODESYS metrics
        codesys_pass = sum(1 for r in codesys_results if r.get('codesys_passed', False))
        codesys_total = len(codesys_results)
        codesys_rate = codesys_pass / codesys_total * 100 if codesys_total > 0 else 0

        # Calculate agreement
        both_pass = sum(1 for a, c in zip(antlr_results, codesys_results)
                       if a.get('is_solved', False) and c.get('codesys_passed', False))
        both_fail = sum(1 for a, c in zip(antlr_results, codesys_results)
                       if not a.get('is_solved', False) and not c.get('codesys_passed', False))
        antlr_only = sum(1 for a, c in zip(antlr_results, codesys_results)
                        if a.get('is_solved', False) and not c.get('codesys_passed', False))
        codesys_only = sum(1 for a, c in zip(antlr_results, codesys_results)
                         if not a.get('is_solved', False) and c.get('codesys_passed', False))

        agreement_rate = (both_pass + both_fail) / len(antlr_results) * 100

        print(f"\n📊 Overall Validation Comparison:")
        print("-" * 100)
        print(f"{'Metric':<40} {'ANTLR':>15} {'CODESYS':>15} {'Difference':>15}")
        print("-" * 100)
        print(f"{'Total Tasks':<40} {antlr_total:>15} {codesys_total:>15} {'N/A':>15}")
        print(f"{'Passed Tasks':<40} {antlr_pass:>15} {codesys_pass:>15} {codesys_pass-antlr_pass:>+15}")
        print(f"{'Pass Rate (%)':<40} {antlr_rate:>15.2f} {codesys_rate:>15.2f} {codesys_rate-antlr_rate:>+15.2f}")

        print(f"\n🔍 Validation Agreement Analysis:")
        print("-" * 100)
        print(f"Both ANTLR and CODESYS passed:  {both_pass:>4} / {len(antlr_results)} ({both_pass/len(antlr_results)*100:.1f}%)")
        print(f"Both ANTLR and CODESYS failed:  {both_fail:>4} / {len(antlr_results)} ({both_fail/len(antlr_results)*100:.1f}%)")
        print(f"ANTLR passed, CODESYS failed:   {antlr_only:>4} / {len(antlr_results)} ({antlr_only/len(antlr_results)*100:.1f}%)")
        print(f"ANTLR failed, CODESYS passed:   {codesys_only:>4} / {len(antlr_results)} ({codesys_only/len(antlr_results)*100:.1f}%)")
        print(f"Overall agreement rate:          {agreement_rate:>6.1f}%")

        # Category-wise comparison
        print(f"\n📈 Category-wise Validation Comparison:")
        print("-" * 100)
        print(f"{'Category':<35} {'ANTLR':>10} {'CODESYS':>10} {'Agreement':>10}")
        print("-" * 100)

        categories = set(r.get('true_category', 'Unknown') for r in antlr_results)

        for category in sorted(categories):
            cat_antlr = [r for r in antlr_results if r.get('true_category') == category]
            cat_codesys = [r for r in codesys_results if r.get('true_category') == category]

            cat_antlr_pass = sum(1 for r in cat_antlr if r.get('is_solved', False))
            cat_codesys_pass = sum(1 for r in cat_codesys if r.get('codesys_passed', False))

            cat_antlr_rate = cat_antlr_pass / len(cat_antlr) * 100 if cat_antlr else 0
            cat_codesys_rate = cat_codesys_pass / len(cat_codesys) * 100 if cat_codesys else 0

            # Calculate agreement for this category
            cat_both_pass = sum(1 for a, c in zip(cat_antlr, cat_codesys)
                              if a.get('is_solved', False) and c.get('codesys_passed', False))
            cat_both_fail = sum(1 for a, c in zip(cat_antlr, cat_codesys)
                              if not a.get('is_solved', False) and not c.get('codesys_passed', False))
            cat_agreement = (cat_both_pass + cat_both_fail) / len(cat_antlr) * 100 if cat_antlr else 0

            print(f"{category:<35} {cat_antlr_rate:>9.1f}% {cat_codesys_rate:>9.1f}% {cat_agreement:>9.1f}%")

        print("=" * 100)

        return {
            'antlr_metrics': {
                'total': antlr_total,
                'passed': antlr_pass,
                'pass_rate': antlr_rate
            },
            'codesys_metrics': {
                'total': codesys_total,
                'passed': codesys_pass,
                'pass_rate': codesys_rate
            },
            'agreement': {
                'both_pass': both_pass,
                'both_fail': both_fail,
                'antlr_only': antlr_only,
                'codesys_only': codesys_only,
                'agreement_rate': agreement_rate
            }
        }


def main():
    """Main function"""
    parser = argparse.ArgumentParser(
        description="Validate Single Agent results using CODESYS compilation service"
    )

    parser.add_argument(
        '--input_file',
        type=str,
        required=True,
        help='Path to Single Agent baseline results JSON file'
    )

    parser.add_argument(
        '--output_file',
        type=str,
        default='comparison/results/single_agent_codesys_validated.json',
        help='Path to save validated results'
    )

    parser.add_argument(
        '--codesys_host',
        type=str,
        default=None,
        help='CODESYS server host (auto-detect if not specified)'
    )

    parser.add_argument(
        '--codesys_port',
        type=int,
        default=None,
        help='CODESYS server port (auto-detect if not specified)'
    )

    args = parser.parse_args()

    # Load Single Agent results
    logger = logging.getLogger("CODESYSValidator")
    logger.info(f"Loading results from {args.input_file}")

    try:
        with open(args.input_file, 'r', encoding='utf-8') as f:
            single_agent_results = json.load(f)
        logger.info(f"Loaded {len(single_agent_results)} results")
    except Exception as e:
        logger.error(f"Error loading results: {e}")
        return

    # Initialize validator
    try:
        validator = CODESYSValidator(args.codesys_host, args.codesys_port)
    except Exception as e:
        logger.error(f"Error initializing CODESYS validator: {e}")
        logger.error("Make sure CODESYS compilation service is running")
        return

    # Validate all results
    try:
        validated_results = validator.validate_batch(single_agent_results)
    except Exception as e:
        logger.error(f"Error during validation: {e}")
        return

    # Save validated results
    os.makedirs(os.path.dirname(args.output_file), exist_ok=True)
    with open(args.output_file, 'w', encoding='utf-8') as f:
        json.dump(validated_results, f, indent=2, ensure_ascii=False)

    logger.info(f"Validated results saved to {args.output_file}")

    # Generate comparison report
    comparison_report = validator.generate_comparison_report(single_agent_results, validated_results)

    # Save comparison report
    report_file = args.output_file.replace('.json', '_comparison_report.json')
    with open(report_file, 'w', encoding='utf-8') as f:
        json.dump(comparison_report, f, indent=2, ensure_ascii=False)

    logger.info(f"Comparison report saved to {report_file}")
    logger.info("✅ CODESYS validation completed!")


if __name__ == "__main__":
    main()
